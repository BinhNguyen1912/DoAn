import { ApiProperty } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { IsDate, IsInt, IsNumber, IsOptional, IsUUID, Max, Min } from 'class-validator';
import { ALERT_STATUSES, type AlertStatus } from '../../alerts/alert-status.js';

export class CreateEventDto {
  @ApiProperty({ format: 'uuid', description: 'Idempotency key generated by Edge AI' })
  @IsUUID()
  eventId!: string;

  @ApiProperty({ example: 1 })
  @IsInt()
  @Min(1)
  zoneId!: number;

  @ApiProperty({ type: String, format: 'date-time', description: 'When Edge AI confirmed the intrusion' })
  @Type(() => Date)
  @IsDate()
  detectedAt!: Date;

  @ApiProperty({ minimum: 0, maximum: 1 })
  @IsNumber()
  @Min(0)
  @Max(1)
  confidence!: number;
}

export class AlertAttemptResponseDto {
  @ApiProperty() id!: number;
  @ApiProperty() deviceId!: number;
  @ApiProperty({ enum: ALERT_STATUSES }) status!: AlertStatus;
  @ApiProperty({ type: String, nullable: true }) error!: string | null;
  @ApiProperty({ type: String, format: 'date-time' }) updatedAt!: Date;
}

export class EventResponseDto {
  @ApiProperty({ format: 'uuid' }) eventId!: string;
  @ApiProperty() zoneId!: number;
  @ApiProperty({ type: String, format: 'date-time' }) detectedAt!: Date;
  @ApiProperty() confidence!: number;
  @ApiProperty({ type: String, format: 'date-time' }) receivedAt!: Date;
  @ApiProperty({ type: String, nullable: true }) evidencePath!: string | null;
  @ApiProperty({ type: [AlertAttemptResponseDto] }) alertAttempts!: AlertAttemptResponseDto[];
}

export class ListEventsQueryDto {
  @ApiProperty({ required: false, minimum: 1, maximum: 200, default: 50 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(200)
  limit: number = 50;

  @ApiProperty({ required: false, minimum: 0, default: 0 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(0)
  offset: number = 0;
}

export class EventListResponseDto {
  @ApiProperty({ type: [EventResponseDto] }) items!: EventResponseDto[];
  @ApiProperty() total!: number;
}
